"""Kaggle notebook helper: detect the competition data root and write overrides.

Local usage (prints diagnostics only)::

    python -m src.kaggle_setup

On Kaggle (``/kaggle`` exists)::

    python -m src.kaggle_setup                 # writes configs/_kaggle.yaml
    python -m src.kaggle_setup --apply configs/xlsr.yaml
                                               # writes configs/xlsr.kaggle.yaml
                                               #   extends: xlsr.yaml + Kaggle paths

The generated override file only touches path-ish keys (``data_root``,
``output_dir``, ``oof_dir``, ``num_workers``) so the same source tree works in
both environments.
"""

from __future__ import annotations

import argparse
import logging
import os
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence

import yaml

from .config import load_config, setup_logging

LOG = logging.getLogger("kaggle_setup")

KAGGLE_INPUT = Path("/kaggle/input")
KAGGLE_WORKING = Path("/kaggle/working")


def is_kaggle() -> bool:
    return KAGGLE_INPUT.exists()


def candidate_roots(base: Path = KAGGLE_INPUT) -> List[Path]:
    """Directories under ``/kaggle/input`` that look like the competition data."""
    if not base.exists():
        return []
    roots: List[Path] = []
    for entry in sorted(base.iterdir()):
        if not entry.is_dir():
            continue
        has_test = (entry / "test.csv").exists()
        has_train = (entry / "train.csv").exists()
        if has_test or has_train:
            roots.append(entry)
        else:  # some archives nest one level deeper
            for sub in sorted(entry.iterdir()):
                if sub.is_dir() and ((sub / "test.csv").exists() or (sub / "train.csv").exists()):
                    roots.append(sub)
    # prefer directories that have both files, then shorthand ones
    roots.sort(key=lambda p: (not (p / "test.csv").exists(), not (p / "train.csv").exists(), str(p)))
    return roots


def detect_data_root(base: Path = KAGGLE_INPUT) -> Optional[Path]:
    roots = candidate_roots(base)
    return roots[0] if roots else None


def kaggle_overrides(data_root: Path, out_root: Optional[Path] = None) -> Dict[str, object]:
    out_root = out_root or (KAGGLE_WORKING / "runs" if KAGGLE_WORKING.exists() else Path("runs"))
    oof_root = out_root.parent / "oof" if out_root.name == "runs" else out_root / "oof"
    return {
        "data_root": str(data_root),
        "output_dir": str(out_root),
        "oof_dir": str(oof_root),
        "num_workers": 2,  # notebooks: keep DataLoader workers low
    }


def write_override(path: Path, payload: Dict[str, object], extends: Optional[str] = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    data: Dict[str, object] = {}
    if extends:
        data["extends"] = extends
    data.update(payload)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# AUTO-GENERATED by src.kaggle_setup - safe to edit/delete\n")
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True)
    return path


def apply_to_config(config_path: str, out_path: Optional[str] = None, data_root: Optional[str] = None) -> Optional[Path]:
    """Write ``<config>.kaggle.yaml`` (extends the original + Kaggle paths)."""
    root = Path(data_root) if data_root else detect_data_root()
    if root is None:
        LOG.error("No competition data found under %s (pass --data-root to force one)", KAGGLE_INPUT)
        return None
    cfg_path = Path(config_path)
    out = Path(out_path) if out_path else cfg_path.with_suffix(".kaggle.yaml")
    extends = os.path.relpath(cfg_path, out.parent)
    return write_override(out, kaggle_overrides(root), extends=extends)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="python -m src.kaggle_setup", description="Kaggle data-root detection + config overrides.")
    parser.add_argument("--apply", nargs="*", default=[], metavar="CONFIG", help="Configs to turn into *.kaggle.yaml files.")
    parser.add_argument("--out", default=None, help="Override output path (only with a single --apply).")
    parser.add_argument("--data-root", default=None, help="Force this data root instead of auto-detecting /kaggle/input/*.")
    parser.add_argument("--force", action="store_true", help="Write configs/_kaggle.yaml even outside Kaggle.")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    setup_logging()

    print(f"cwd:              {os.getcwd()}")
    print(f"python:           {sys.version.split()[0]}")
    print(f"/kaggle exists:   {is_kaggle()}")

    roots = candidate_roots()
    if roots:
        print("detected data roots:")
        for root in roots:
            has = [name for name in ("train.csv", "test.csv", "sample_submission.csv") if (root / name).exists()]
            print(f"  {root}   ({', '.join(has)})")
    else:
        local_data = Path("data")
        if (local_data / "train.csv").exists():
            print(f"detected local data root: {local_data.resolve()}")

    written: List[Path] = []
    if args.apply:
        for config_path in args.apply:
            path = apply_to_config(
                config_path, args.out if len(args.apply) == 1 else None, data_root=args.data_root
            )
            if path is not None:
                written.append(path)
                print(f"wrote {path}  (extends {os.path.relpath(config_path, path.parent)})")
                load_config(path)  # fail fast if the override does not parse
    elif is_kaggle() or args.force or args.data_root:
        root = Path(args.data_root) if args.data_root else detect_data_root()
        if root is None:
            LOG.error("No competition data found under %s", KAGGLE_INPUT)
            return 1
        path = write_override(Path("configs/_kaggle.yaml"), kaggle_overrides(root))
        written.append(path)
        print(f"wrote {path}  (data_root={root})")
        print("Use it from any config with:  extends: _kaggle.yaml")
    else:
        print("not on Kaggle: nothing written (use --apply configs/x.yaml to preview an override)")

    if written:
        print("\nto use in a notebook:")
        print("  1. copy src/ + configs/ (or the whole repo) into your Kaggle notebook")
        print("  2. run: python -m src.kaggle_setup --apply configs/xlsr.yaml")
        print("  3. train: python -m src.train_ssl --config configs/xlsr.kaggle.yaml "
              f"--out {kaggle_overrides(detect_data_root() or Path('data'))['output_dir']}/xlsr")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
